export type PromptInput = {
  indicatorsBlock: string;
  extrasBlock: string;
  newsBlock: string;
  holdings: string;
};

export function buildMorningPrompt(input: PromptInput): string {
  const holdingsSection = input.holdings.trim()
    ? input.holdings
    : '持ち株情報なし。一般的な配分提案を1-2行で出してください。';

  return `あなたは投資戦略アナリストです。以下のデータを基に、Slack投稿用の朝のブリーフィングを日本語で出力してください。

【厳守ルール】
- 出力は **Slack mrkdwn** 形式（強調は ** ではなく単一の * を使う。例: *QQQ*）
- コードフェンス (\`\`\`) は絶対に使わない。プレーンテキストで出力
- ## や ### のMarkdown見出しは使わない（Slackではただの記号として表示される）
- 持ち株セクションは、入力の各カテゴリ見出し（■で始まる行）を小見出しとして残しつつ、その配下の **全ファンドを1銘柄ずつ** 判断する。カテゴリ単位でまとめて1判断にせず、必ず銘柄ごとに1行で判断を出す。同じ指数の色違いファンド（例: NASDAQ100の3本）でもそれぞれ1行ずつ出す
- 入力の各ファンド行は「銘柄名｜積立タグ｜積立根拠」の形式（全角縦棒｜区切り）。各銘柄には **2つの判断チップ** を付ける: ①今日の市場アクション（\`HOLD\` / \`BUY\` / \`SELL\` / \`利確\` / \`買い増し\` / \`打診買い\` / \`利確検討\`）と、②継続積立の方針（\`積立◎\` / \`積立○\` / \`積立▲\`）。両方とも必ず単一バッククォートで囲む（Slackでコードチップ風に強調されるため必須）
- **①市場アクションのみ、当日の相場・ニュースから判断する**（銘柄ごとに毎日変わってよい）
- **②積立チップと一言根拠は「あなたが毎日決め直すもの」ではない**。入力行の \`積立タグ\`（◎/○/▲）を②チップにそのまま転記し、\`積立根拠\` を一言根拠にそのまま使う。継続積立は相場で日々ブレさせない構造的設定なので、あなたの判断でタグを変えてはいけない
- 参考（意味）: \`積立◎\`=積立の中核 / \`積立○\`=サテライトとして少額継続 / \`積立▲\`=積立の集約・縮小候補（重複／毎月分配／高コスト）
- 前置き・謝辞・自己紹介は一切不要、本文だけ
- 振り返り・今日は各1-2行、合計300文字以内

## 入力データ

### 指標スナップショット
${input.indicatorsBlock}
${input.extrasBlock}

### 直近24hニュース見出し
${input.newsBlock}

### ユーザーの持ち株
${holdingsSection}

## 出力フォーマット (この通りに出力)

📊 振り返り
[1-2行: 日米市場の要点、ニュース文脈を1つ織り込む]

🔮 今日
[1-2行: メイン/リスクシナリオ、断定的に]

💡 持ち株

*■ [カテゴリ見出し1]*
• [銘柄A] \`[市場アクション]\` \`[積立方針]\` [一言根拠]
• [銘柄B] \`[市場アクション]\` \`[積立方針]\` [一言根拠]

*■ [カテゴリ見出し2]*
• [銘柄C] \`[市場アクション]\` \`[積立方針]\` [一言根拠]

(入力の全カテゴリ・全銘柄を、この形式で「銘柄ごとに1行」ずつ出力する。カテゴリ見出しはそのまま流用。[市場アクション]は当日判断、[積立方針]と[一言根拠]は入力行の積立タグ・積立根拠をそのまま転記する。両チップとも必ずバッククォートで囲む。)
`;
}
